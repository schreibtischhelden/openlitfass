// Package instance describes one deployment of openlitfass (e.g.
// "weissens.ee"): a directory with an instance.json plus the instance's own
// sources, inbox, category registry, site assets and generated data.
//
// The core repository (this one) contains no instance-specific content at
// all - everything that makes a calendar "about Weißensee" lives in the
// instance directory. See https://docs.openlitfass.org/?page=configuration for the full layout.
//
//	<instance>/
//	  instance.json      Config below
//	  categories.json    category -> pictogram registry (input)
//	  sources/           one *.json per event source
//	  inbox/             hand-authored single events
//	  site/              static overrides merged over web/ (theme.css, logo.svg, fonts, ...)
//	  data/              generated by cmd/fetch (events.json, categories.json)
package instance

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// Config is the content of <instance>/instance.json.
type Config struct {
	// Name is the short brand name shown in the header, e.g. "weissens.ee".
	Name string `json:"name"`
	// Title is the HTML <title>, e.g. "weissens.ee – Events in Weißensee".
	// Defaults to Name.
	Title string `json:"title,omitempty"`
	// Description is the HTML meta description.
	Description string `json:"description,omitempty"`
	// BaseURL is the public URL of the site, e.g. "https://weissens.ee".
	// Used as fallback link for events without their own URL. Optional.
	BaseURL string `json:"baseUrl,omitempty"`
	// Timezone is the IANA zone all event times are expressed in.
	// Defaults to model.DefaultTimezone.
	Timezone string `json:"timezone,omitempty"`
	// Language is the HTML lang attribute. Defaults to "de".
	Language string `json:"language,omitempty"`
	// ThemeColor is the <meta name="theme-color"> value and the PWA
	// manifest's theme/background color. Optional.
	ThemeColor string `json:"themeColor,omitempty"`
	// ShortName is the PWA app name under the home-screen icon (max ~12
	// characters). Defaults to Name.
	ShortName string `json:"shortName,omitempty"`
	// About is the intro text on the frontend's "Über" page. Plain text,
	// blank lines separate paragraphs.
	About string `json:"about,omitempty"`
	// ImprintURL / PrivacyURL link the legally required Impressum and
	// Datenschutzerklärung. Can be absolute or relative to the site (e.g.
	// "impressum.html" placed in site/).
	ImprintURL string `json:"imprintUrl,omitempty"`
	PrivacyURL string `json:"privacyUrl,omitempty"`
	// SubmitURL is where people can report an event that's missing (a
	// form, a mailto: link, ...). Shown on the "Über" page. Optional.
	SubmitURL string `json:"submitUrl,omitempty"`
	// IssuesURL is the instance's issue tracker for errors and wishes about
	// this site (events, sources, places), e.g.
	// "https://github.com/weissensee/weissens.ee/issues". Shown on the "Über"
	// page next to the openLitfass tracker. For a GitHub tracker the page
	// links straight to the bug.yml / feature.yml issue forms. Optional.
	IssuesURL string `json:"issuesUrl,omitempty"`
	// FetchTimeoutMinutes limits one whole fetch run, in which the sources
	// are fetched one after another. Defaults to 5; raise it for instances
	// with many sources or sources that pace their requests
	// (requestDelaySeconds).
	FetchTimeoutMinutes int `json:"fetchTimeoutMinutes,omitempty"`
}

// DefaultFetchTimeout is the time limit of a fetch run when instance.json
// sets no fetchTimeoutMinutes.
const DefaultFetchTimeout = 5 * time.Minute

// FetchTimeout is the time limit of one fetch run.
func (c Config) FetchTimeout() time.Duration {
	if c.FetchTimeoutMinutes <= 0 {
		return DefaultFetchTimeout
	}
	return time.Duration(c.FetchTimeoutMinutes) * time.Minute
}

// Instance is a loaded instance directory.
type Instance struct {
	Dir    string
	Config Config
}

// Load reads <dir>/instance.json. It is required: without it there is no
// way to tell an instance directory from any other directory, and running
// fetch against the wrong directory would write status fields and delete
// inbox files in places it shouldn't.
func Load(dir string) (Instance, error) {
	path := filepath.Join(dir, "instance.json")
	data, err := os.ReadFile(path)
	if err != nil {
		return Instance{}, fmt.Errorf("read %s: %w (is %q an instance directory?)", path, err, dir)
	}
	var c Config
	if err := json.Unmarshal(data, &c); err != nil {
		return Instance{}, fmt.Errorf("parse %s: %w", path, err)
	}
	if strings.TrimSpace(c.Name) == "" {
		return Instance{}, fmt.Errorf(`%s: "name" is required`, path)
	}
	if c.Title == "" {
		c.Title = c.Name
	}
	if c.Language == "" {
		c.Language = "de"
	}
	if c.ShortName == "" {
		c.ShortName = c.Name
	}
	return Instance{Dir: dir, Config: c}, nil
}

// Path joins elem onto the instance directory.
func (i Instance) Path(elem ...string) string {
	return filepath.Join(append([]string{i.Dir}, elem...)...)
}

func (i Instance) SourcesDir() string       { return i.Path("sources") }
func (i Instance) InboxDir() string         { return i.Path("inbox") }
func (i Instance) CategoryRegistry() string { return i.Path("categories.json") }
func (i Instance) HolidaysFile() string     { return i.Path("holidays.json") }
func (i Instance) SiteDir() string          { return i.Path("site") }
func (i Instance) DataDir() string          { return i.Path("data") }
func (i Instance) EventsOutput() string     { return i.Path("data", "events.json") }
func (i Instance) CategoriesOutput() string { return i.Path("data", "categories.json") }

// Dir resolves the instance directory: the first command-line argument if
// given, else $OL_INSTANCE_DIR, else the current directory.
func Dir(args []string) string {
	if len(args) > 0 && args[0] != "" {
		return args[0]
	}
	if v := os.Getenv("OL_INSTANCE_DIR"); v != "" {
		return v
	}
	return "."
}
